"""UI language. Source strings are Chinese; EN maps them to English. The parent picks the language in Settings
(default English). Strings may carry {placeholders} filled by keyword arguments."""
from __future__ import annotations

from . import db

LANGS = {"en": "English", "zh": "中文"}
DEFAULT = "en"
_lang = DEFAULT


def load() -> None:
    global _lang
    with db.tx() as c:
        v = db.kv_get(c, "ui_lang", DEFAULT)
    _lang = v if v in LANGS else DEFAULT


def set_lang(lang: str) -> None:
    global _lang
    if lang not in LANGS:
        raise ValueError(lang)
    with db.tx() as c:
        db.kv_set(c, "ui_lang", lang)
    _lang = lang


def lang() -> str:
    return _lang


def t(text: str, /, **kw: object) -> str:
    out = EN.get(text, text) if _lang == "en" else text
    return out.format(**kw) if kw else out


